"""Проверка «ответ по вопросу».

Проверка фактов не ловит ответ на соседний вопрос: на «Какой срок согласования?» модель пересказывает
пороги суммы — все факты настоящие, но вопрос не отвечен. Две ступени:

1. Эвристика по типу вопроса (без модели, мгновенно):
   «какой срок / сколько дней» → в ответе должен быть срок (число + дни/часы…) или прямое «срок не указан»;
   «где» → место (путь, диск, папка, портал, система, отдел…);
   «кто / кому / кем» → лицо (ФИО или должность, подразделение);
   «сколько» → число.
2. Короткий запрос к модели: «Отвечает ли ответ прямо на вопрос? да/нет» (RELEVANCE_LLM_CHECK).
"""
import json
import re

_FIO = r"[А-ЯЁ][а-яё]+\s+[А-ЯЁ]\.\s?[А-ЯЁ]\."
_ROLE = (r"директор|бухгалтер|юрист|руководител|начальник|менеджер|специалист|методолог|отдел|департамент|"
         r"служб|управлени|бухгалтери|секретар|кадр|администратор|"
         # роли проектной деятельности из регламентов заказчика
         r"архитектор|координатор|сотрудник|аккаунт|исполнител|\bрп\b|\bss\b|\bам\b|\btps\b|\bbdm\b|\bпа\b")

_DATE = r"\d{1,2}\.\d{1,2}\.\d{4}|\d{1,2}\s+(?:январ|феврал|март|апрел|ма[яй]|июн|июл|август|сентябр|октябр|ноябр|декабр)\w*|с\s+(?:январ|феврал|март|апрел|ма[яй]|июн|июл|август|сентябр|октябр|ноябр|декабр)\w*"

QUESTION_TYPES = [
    ("срок",
     re.compile(r"(?i)\b(?:как\w*|каков\w*)\s+срок|\bсколько\s+(?:\w+\s+)?(?:дней|времени|часов|недель)|\bв\s+течение\s+как|\bкак\s+долго"),
     re.compile(r"(?i)\d+\s*(?:рабоч\w*\s+|календарн\w*\s+)?(?:дн|день|час|недел|месяц)|срок\w*\s+не\s+(?:указан|установлен|определ)")),
    ("дата",
     re.compile(r"(?i)\bкогда\b|\bс\s+какого\s+(?:числа|момента|дня)"),
     re.compile(rf"(?i){_DATE}")),
    ("место",
     re.compile(r"(?i)\bгде\b|\bв\s+какой\s+папке|\bна\s+каком\s+(?:диске|портале|сайте|ресурсе)|\bкуда\s+(?:сохран|положить|загруз)"),
     re.compile(r"(?i)[A-Za-z]:\\|\\\\|https?://|\bдиск|папк|портал|сайт|систем|кабинет|отдел|канал|раздел|хранилищ|архив")),
    ("лицо",
     re.compile(r"(?i)\b(?:кто|кем|кому|кого|чья|чей|чьё|чье)\b"),
     re.compile(rf"{_FIO}|(?i:{_ROLE})")),
]
_HOW_MANY = re.compile(r"(?i)\bсколько\s+(\w+)")

# Проверяющий видит вопрос, ответ И источник: проверяет и «ответ на вопрос», и «ответ следует из источника».
# Без источника 7B пропускала додуманные ответы («госпошлину платит Смирнов» — имя настоящее, связь выдумана).
# Примеры в промпте обязательны: без них qwen2.5:1.5b отвечает «нет» на всё.
# Замер 23.11.2026 на 10 парах: 1.5B — 8/10, 7B — 9/10, плохих ответов не пропущено ни одной моделью.
JUDGE_PROMPT = (
    "Ты проверяешь ответ корпоративного помощника. Даны вопрос, ответ и источник.\n"
    "Ответ засчитывается, только если ОДНОВРЕМЕННО:\n"
    "1) он прямо отвечает на заданный вопрос;\n"
    "2) то, что отвечает на вопрос, прямо написано в источнике (а не додумано по соседним фактам).\n"
    "Примеры:\n"
    'Источник: Пропуска выдаёт охрана. Вопрос: Кто выдаёт пропуска? Ответ: Пропуска выдаёт охрана. -> {"ok": true}\n'
    'Источник: Пропуска выдаёт охрана. Вопрос: Кто оплачивает парковку? Ответ: Парковку оплачивает охрана. -> {"ok": false}\n'
    'Источник: Отчёт сдаётся в бухгалтерию. Вопрос: Сколько дней на отчёт? Ответ: Отчёт сдаётся в бухгалтерию. -> {"ok": false}\n'
    'Источник: Старый порядок отменён. Вопрос: Действует ли старый порядок? Ответ: Нет, старый порядок отменён. -> {"ok": true}\n'
    'Верни ТОЛЬКО JSON: {"ok": true} или {"ok": false}'
)

# Модель честно пишет «в источниках нет», но всё равно ссылается на источник — это отсутствие ответа
_NO_ANSWER = re.compile(
    r"(?i)(?:нет|не\s+(?:указан\w*|найден\w*|содерж\w*|приведен\w*|упомина\w*|предусмотрен\w*|описан\w*))\s+"
    r"в\s+(?:предоставленных\s+|найденных\s+)?(?:источник\w*|документ\w*)"
    r"|в\s+(?:предоставленных\s+|найденных\s+)?(?:источник\w*|документ\w*)\s+(?:нет|не\s+(?:указан|найден|содерж|приведен|упомина|описан)\w*)"
    r"|информаци\w+\s+(?:об\s+этом\s+|по\s+этому\s+вопросу\s+)?(?:нет|отсутству)")


def says_no_answer(answer: str) -> bool:
    return bool(_NO_ANSWER.search(answer))


def _how_many_check(question: str, answer: str) -> tuple[bool, str] | None:
    """«Сколько экземпляров» → в ответе число экземпляров; «сколько стоит» → сумма в рублях."""
    m = _HOW_MANY.search(question)
    if not m:
        return None
    word = m.group(1).lower()
    if word.startswith("сто"):  # стоит, стоимость
        expected = re.compile(r"(?i)\d[\d\s]*\s*(?:руб|₽|р\.)|бесплатн")
    else:
        expected = re.compile(rf"(?i)\d+\s*{re.escape(word[:5])}")
    if expected.search(answer):
        return True, "тип вопроса «количество»: ответ подходит"
    return False, f"на вопрос «сколько {word}» в ответе нет количества"


def question_type(question: str) -> str | None:
    for name, ask, _ in QUESTION_TYPES:
        if ask.search(question):
            return name
    return "количество" if _HOW_MANY.search(question) else None


def heuristic_check(question: str, answer: str) -> tuple[bool, str]:
    """(ответ подходит, пояснение). Неизвестный тип вопроса — проверка не применяется."""
    for name, ask, expected in QUESTION_TYPES:
        if ask.search(question):
            if expected.search(answer):
                return True, f"тип вопроса «{name}»: ответ подходит"
            return False, f"на вопрос типа «{name}» в ответе нет ожидаемого ({name})"
    how_many = _how_many_check(question, answer)
    if how_many:
        return how_many
    return True, "тип вопроса не определён — эвристика не применялась"


def llm_check(question: str, answer: str, call_llm, source: str = "") -> tuple[bool | None, str]:
    """(ответ подходит / None — проверка не удалась, пояснение). call_llm(messages) → текст.
    source — текст документа, на который сослалась модель."""
    try:
        raw = call_llm([
            {"role": "system", "content": JUDGE_PROMPT},
            {"role": "user", "content": f"Источник: {source}\nВопрос: {question}\nОтвет: {answer}"},
        ])
        start, end = raw.find("{"), raw.rfind("}")
        data = json.loads(raw[start:end + 1])
        verdict = data["ok"] if "ok" in data else data["answers_question"]
        if isinstance(verdict, str):
            verdict = verdict.strip().lower() in ("true", "да", "yes")
        return bool(verdict), "модель-проверяющий: " + (
            "ответ по вопросу и следует из источника" if verdict else "ответ не на вопрос или не следует из источника")
    except (ValueError, KeyError, TypeError) as exc:
        return None, f"модель-проверяющий не дала вердикт ({type(exc).__name__})"
